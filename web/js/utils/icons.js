/**
 * 构造统一规格的 SVG 字符串。
 * @param {keyof typeof SVG_ICONS} name - 图标名称
 * @param {number} [size=14] - 图标尺寸 (宽高像素)
 * @param {string} [className=""] - 额外样式类名
 * @returns {string} 完整的 SVG 标签字符串
 */
export function renderIcon(name, size = 14, className = "") {
    const inner = SVG_ICONS[name] || SVG_ICONS.messageSquare;
    const classes = className ? `class="pv-icon ${className}"` : `class="pv-icon"`;
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ${classes} style="display:inline-block; vertical-align:middle; flex-shrink:0;">${inner}</svg>`;
}

/**
 * 创建包含 SVG 的 DOM 元素。
 * @param {keyof typeof SVG_ICONS} name - 图标名称
 * @param {number} [size=14] - 图标尺寸
 * @param {string} [className=""] - 额外样式类名
 * @returns {HTMLElement} 包含 SVG 的 span 容器
 */
export function createIconElement(name, size = 14, className = "") {
    const span = document.createElement("span");
    span.style.display = "inline-flex";
    span.style.alignItems = "center";
    span.style.justifyContent = "center";
    span.innerHTML = renderIcon(name, size, className);
    return span;
}